function bePlace(value) {
  if (placesBe[value]) {
    return placesBe[value];
  }
  return String(value)
    .replace(/ский/g, "скі")
    .replace(/ская/g, "ская")
    .replace(/ское/g, "скае")
    .replace(/район/g, "раён")
    .replace(/область/g, "вобласць")
    .replace(/и/g, "і")
    .replace(/И/g, "І");
}

export function placeName(value, lang) {
  if (lang === "be" && value) {
    return bePlace(value);
  }
  if (lang !== "en" || !value) {
    return value || "";
  }
  if (places[value]) {
    return places[value];
  }
  return String(value)
    .split("")
    .map((char) => letters[char.toLowerCase()] ?? char)
    .join("");
}

export function categoryName(category, lang, t) {
  const slug = category?.slug || "";
  const bySlug = {
    architecture: "catArchitecture",
    museum: "catMuseum",
    park: "catPark",
    monument: "catMonument",
    religion: "catReligion",
    nature: "catNature",
  };
  if ((lang === "en" || lang === "be") && bySlug[slug]) {
    return t(bySlug[slug]);
  }
  return category?.title || "";
}
